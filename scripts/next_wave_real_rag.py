class RealRAGRunError(RuntimeError):
    """A real-run preflight or execution boundary failed safely."""

    def __init__(
        self,
        code: str,
        message: str = "real RAG execution failed",
        *,
        provider_ledger: Mapping[str, object] | None = None,
    ) -> None:
        super().__init__(message)
        self.code = code
        self.provider_ledger = dict(provider_ledger) if provider_ledger is not None else None


@dataclass(frozen=True, slots=True)
class CaseSelection:
    """A validated, bounded case selection independent of execution."""

    cases: tuple[RAGCase, ...]
    requested_ids: tuple[str, ...] = ()
    limit: int | None = None

    @property
    def is_full_set(self) -> bool:
        return len(self.cases) == 72

    def safe_dict(self) -> dict[str, object]:
        return {
            "count": len(self.cases),
            "full_set": self.is_full_set,
            "requested_ids": list(self.requested_ids),
            "limit": self.limit,
            "case_ids": [case.case_id for case in self.cases],
        }


