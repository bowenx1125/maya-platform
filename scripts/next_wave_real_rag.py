"""Execute the frozen synthetic RAG acceptance cases through Maya's real ports.

The default command is a read-only dry run.  It validates and selects the
committed fixture set without constructing a provider, opening a database, or
writing an artifact.  ``--execute-real`` is an explicit operator boundary:
the selected cases run against a disposable SQLite application database and a
temporary data root inside the required output directory.  Knowledge is
imported and chunked through the existing Markdown/domain seams, snapshots are
published through the real embedding runtime, query vectors are generated by
the controlled SQL query runtime, and answers are produced by the real
``SegmentLLMRuntime``.  No fallback answer or hand-picked source is inserted.

This script deliberately has no retry loop.  The segment runtime's bounded
structure-repair attempt is the only retry it can exercise; provider transport
outcomes remain terminal and are recorded with a safe code.  Provider output
envelopes, credentials, headers, and supplier metadata are never persisted or
printed.
"""

