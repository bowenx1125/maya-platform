def _query_service(
    database: Database,
    *,
    reviewed: RealRAGSettings,
    owner: _Owner,
    published: _PublishedOwner,
    rows: _TurnRows,
    context: GenerationContext,
    subqueries: Sequence[TurnSubquery],
    embedding_adapter: EmbeddingProvider,
) -> tuple[QueryEmbeddingService, QueryExportPlanV1]:
    del context
    with database.session() as db:
        snapshot = db.get(KnowledgeSnapshot, published.snapshot_id)
        if snapshot is None:
            raise RealRAGRunError("snapshot_missing")
        identity = persisted_snapshot_identity(snapshot)
        if identity.provider != REAL_EMBEDDING_PROVIDER:
            raise RealRAGRunError("snapshot_identity_invalid")
        transcript_hash = compute_mutual_transcript_hash(())
        plan = ensure_real_query_export_manifest(
            database,
            db=db,
            scope_id=rows.debate_id,
            turn_id=rows.turn_id,
            course_id=owner.course_id,
            group_id=owner.group_id,
            agent_version_id=owner.version_id,
            snapshot_id=published.snapshot_id,
            identity=identity,
            transcript_hash=transcript_hash,
            persona_spec_hash=owner.persona_hash,
            subqueries=tuple((item.query_kind, item.text) for item in subqueries),
            policy=reviewed.embedding_policy,
        )
    _confirm_manifest(database, plan.manifest, policy=reviewed.embedding_policy)
    query_hashes = plan.query_hashes
    control = SqlAlchemyQueryControlAdapter(
        database,
        scope_id=rows.debate_id,
        snapshot_id=published.snapshot_id,
        identity=plan.identity,
        policy_hash=reviewed.embedding_policy.policy_hash,
        export_manifest_hash=plan.manifest.manifest_hash,
        build_manifest_hash=plan.build_manifest_hash,
        query_hashes=query_hashes,
        attempt_no=1,
        logical_item_id=f"turn:{rows.turn_id}",
        confirmation_revision=plan.manifest.operation_revision,
        max_requests=SQL_QUERY_MAX_REQUESTS,
        repository=ProviderRepository(database, require_export_confirmation=False),
    )
    controlled = controlled_query_provider(
        embedding_adapter,
        control=control,
        stage_store=SqlAlchemyEmbeddingStageStore(database),
    )
    service = QueryEmbeddingService(
        provider=controlled,
        control=control,
        manifest=control,
        budget=control,
        build_manifest_hash=plan.build_manifest_hash,
    )
    try:
        # The control context covers the whole deterministic query catalog;
        # batch it once before the SQL retriever asks for individual vectors.
        with database.session() as db:
            snapshot = db.get(KnowledgeSnapshot, published.snapshot_id)
            if snapshot is None:
                raise RealRAGRunError("snapshot_missing")
            service.embed_subqueries(snapshot, plan.query_texts)
    except RealRAGRunError:
        raise
    except Exception as exc:
        raise RealRAGRunError(_safe_error_code(exc, "query_embedding_failed")) from exc
    return service, plan


def _execute_enabled_case(
    database: Database,
    data_root: Path,
    reviewed: RealRAGSettings,
    case: RAGCase,
    *,
    fixture_root: Path,
    embedding_adapter: EmbeddingProvider,
    llm_adapter: DashScopeLLMAdapter,
) -> dict[str, object]:
    if case.condition.corpus_path is None:
        raise RealRAGRunError("source_required_for_enabled_case")
    fixture_path = fixture_root / case.condition.corpus_path
    try:
        source_bytes = fixture_path.read_bytes()
    except OSError as exc:
        raise RealRAGRunError("source_read_failed") from exc
    owner = _seed_owner(database, data_root, case=case, source_bytes=source_bytes)
    embedding_started = time.monotonic()
    published = _publish_owner(
        database,
        data_root,
        reviewed,
        owner,
        embedding_adapter=embedding_adapter,
    )
    embedding_duration_ms = int((time.monotonic() - embedding_started) * 1000)
    rows = _create_turn_rows(
        database,
        published,
        question=case.question.question,
        language=case.question.language,
    )
    context = _context(case=case, published=published, rows=rows)
    subqueries = build_segment_subqueries(context)
    query_started = time.monotonic()
    service, query_plan = _query_service(
        database,
        reviewed=reviewed,
        owner=owner,
        published=published,
        rows=rows,
        context=context,
        subqueries=subqueries,
        embedding_adapter=embedding_adapter,
    )
    with database.session() as db:
        retrieval = SqlSnapshotRetriever(db, query_embeddings=service).retrieve(
            published.snapshot_id,
            subqueries,
        )
        receipts = tuple(cast(SnapshotRetrievalReceipt, item) for item in retrieval.receipts)
        snapshot = build_segment_input(
            context,
            persona=context.participant.persona,  # type: ignore[arg-type]
            receipts=receipts,
            round_total=2,
        )
    query_duration_ms = int((time.monotonic() - query_started) * 1000)
    manifest = _llm_manifest(
        debate_id=rows.debate_id,
        turn_id=rows.turn_id,
        snapshot=snapshot,
        receipts=receipts,
        policy=reviewed.llm_policy,
        persona_hash=owner.persona_hash,
    )
    _persist_llm_manifest_and_confirmation(
        database,
        manifest=manifest,
        policy=reviewed.llm_policy,
        owner=owner,
    )
    repository = ProviderRepository(database)
    repository.save_scope_budget(
        rows.debate_id,
        ProviderScopeBudgetV1(
            max_requests=2,
            max_total_tokens=2 * (LLM_INPUT_TOKEN_CAP + LLM_RESERVED_OUTPUT_TOKEN_CAP),
            max_cost_cny=float(2 * LLM_REQUEST_COST_CAP),
            budget_bucket="llm_debate_turn",
        ),
    )
    segment_adapter = SegmentLLMAdapter(
        llm_adapter.config,
        llm_adapter.transport,
        tokenizer=llm_adapter.tokenizer,
        outbound_manifest=LLMOutboundManifestV1(),
    )
    runtime = SegmentLLMRuntime(
        ledger=repository,
        adapter=segment_adapter,
        stage_store=repository,
        publication=None,
        defer_publication=True,
    )
    started = time.monotonic()
    try:
        prepared = runtime.prepare(
            snapshot,
            debate_id=rows.debate_id,
            turn_id=rows.turn_id,
            policy_hash=reviewed.llm_policy.policy_hash,
            manifest_hash=manifest.manifest_hash,
            build_manifest_hash=manifest.build_manifest_hash,
            confirmation_revision=manifest.operation_revision,
            outbound_manifest=LLMOutboundManifestV1(),
            queries=subqueries,
        )
        outcome = runtime.run(prepared, context=context, confirmed=True)
        if outcome.status != "succeeded" or not isinstance(outcome.result, SegmentTurnResult):
            raise RealRAGRunError(
                getattr(outcome, "safe_error_code", None) or "llm_generation_failed"
            )
        operation_id = getattr(outcome.operation, "id", None)
        if not isinstance(operation_id, str) or not operation_id:
            raise RealRAGRunError("llm_operation_missing")
        repository.mark_succeeded(operation_id)
    except RealRAGRunError:
        raise
    except Exception as exc:
        raise RealRAGRunError(_safe_error_code(exc, "llm_generation_failed")) from exc
    duration_ms = int((time.monotonic() - started) * 1000)
    result = outcome.result
    if not isinstance(result, SegmentTurnResult):  # pragma: no cover - guarded above
        raise RealRAGRunError("llm_generation_failed")
    actual_receipt_ids = [item.resolved_evidence_id() for item in receipts]
    retrieved_evidence_ids = list(
        dict.fromkeys(
            label
            for receipt in receipts
            for label in _source_evidence_ids(case, receipt.excerpt or receipt.text)
        )
    )
    source_by_local = {f"S{index}": receipt for index, receipt in enumerate(receipts, start=1)}
    cited_receipts = tuple(
        source_by_local[source_id]
        for item in result.lineage
        for source_id in item.source_ids
        if source_id in source_by_local
    )
    evidence: list[dict[str, object]] = []
    seen_evidence_ids: set[str] = set()
    for receipt in cited_receipts:
        for item in _receipt_report(case, receipt):
            evidence_id = str(item["evidence_id"])
            if evidence_id not in seen_evidence_ids:
                seen_evidence_ids.add(evidence_id)
                evidence.append(item)
    cited = [
        {
            "paragraph_index": item.segment_index,
            "text": item.text,
            "source_ids": [
                source_by_local[source_id].resolved_evidence_id()
                for source_id in item.source_ids
                if source_id in source_by_local
            ],
            "fixture_evidence_ids": list(
                dict.fromkeys(
                    label
                    for source_id in item.source_ids
                    if source_id in snapshot.source_map
                    for label in _source_evidence_ids(case, snapshot.source_map[source_id].text)
                )
            ),
            "reply_to": item.reply_to,
        }
        for item in result.lineage
    ]
    return {
        "case_id": case.case_id,
        "question_id": case.question.question_id,
        "condition": case.condition.condition,
        "repeat": case.repeat,
        "answer": result.speech,
        "retrieval_status": "matched" if receipts else "no_match",
        "grounding_mode": (
            "rag_grounded"
            if result.used_receipts and case.condition.condition in {"correct", "updated"}
            else "mixed"
            if result.used_receipts
            else "general_reasoning"
        ),
        "retrieved_evidence_ids": retrieved_evidence_ids,
        "retrieval_receipt_ids": actual_receipt_ids,
        "retrieved_excerpts": [_retrieved_excerpt_report(item) for item in receipts],
        "evidence": evidence,
        "cited_paragraphs": cited,
        "snapshot_identity": {
            "snapshot_id": published.snapshot_id,
            "provider": query_plan.identity.provider,
            "model_identity_hash": hashlib.sha256(
                query_plan.identity.model_key.encode()
            ).hexdigest(),
            "region": query_plan.identity.region,
            "dimension": query_plan.identity.dimension,
            "policy_version": query_plan.identity.policy_version,
            "build_manifest_hash": published.build_manifest_hash,
        },
        "query_identity": {
            "query_hashes": list(query_plan.query_hashes),
            "query_kinds": list(query_plan.query_kinds),
            "build_manifest_hash": query_plan.build_manifest_hash,
            "manifest_hash": query_plan.manifest.manifest_hash,
        },
        "provider_ledger": {
            "embedding": _provider_ledger_rows(
                repository,
                scope_id=published.build_id,
                provider_operation="embedding",
            ),
            "query": _provider_ledger_rows(
                repository,
                scope_id=rows.debate_id,
                provider_operation="embedding_query",
            ),
            "llm": _provider_ledger_rows(
                repository,
                scope_id=rows.debate_id,
                provider_operation="llm_debate_turn",
            ),
        },
        "timing_ms": {
            "embedding": embedding_duration_ms,
            "query": query_duration_ms,
            "llm": duration_ms,
        },
        **_attempt_report(outcome, default_count=1),
        "safe_error_code": None,
    }


class _DurableDisabledLedger:
    """Retain every disabled-control transition before transport can proceed."""

    def __init__(self, ledger: Any, path: Path) -> None:
        self.ledger = ledger
        self.path = path
        path.parent.mkdir(parents=True, exist_ok=True, mode=0o700)
        self._persist()

    def _persist(self) -> None:
        fields = (
            "id",
            "scope_id",
            "provider_operation",
            "logical_item_id",
            "attempt_no",
            "request_hash",
            "export_manifest_hash",
            "state",
            "request_count",
            "charged_request_count",
            "safe_error_code",
        )
        rows = [
            {field: getattr(item, field, None) for field in fields}
            for item in self.ledger.operations()
        ]
        temporary = self.path.with_suffix(".pending")
        with temporary.open("w", encoding="utf-8") as handle:
            json.dump({"operations": rows}, handle, ensure_ascii=False)
            handle.flush()
            os.fsync(handle.fileno())
        temporary.replace(self.path)

    def __getattr__(self, name: str) -> Any:
        attribute = getattr(self.ledger, name)
        if not callable(attribute):
            return attribute

        @wraps(attribute)
        def invoke(*args: Any, **kwargs: Any) -> Any:
            try:
                return attribute(*args, **kwargs)
            finally:
                self._persist()

        return invoke


