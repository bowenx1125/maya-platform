def _source_evidence_ids(case: RAGCase, text: str) -> tuple[str, ...]:
    """Associate one returned chunk with fixture markers after retrieval.

    This is post-run auditing only.  The gold labels never enter a query,
    prompt, vector, or answer; an evidence label is emitted only when the
    immutable returned chunk contains that condition's marker.
    """

    return tuple(
        evidence.evidence_id
        for evidence in case.condition.expected_evidence
        if evidence.marker in text
    )


def _receipt_report(case: RAGCase, receipt: SnapshotRetrievalReceipt) -> list[dict[str, object]]:
    labels = _source_evidence_ids(case, receipt.excerpt or receipt.text)
    return [
        {
            "evidence_id": label,
            "corpus_path": case.condition.corpus_path,
            "locator": next(
                item.locator
                for item in case.condition.expected_evidence
                if item.evidence_id == label
            ),
            "observed_excerpt": receipt.excerpt or receipt.text,
            "retrieval_evidence_id": receipt.resolved_evidence_id(),
            "source_filename": receipt.source_filename,
            "rank": receipt.rank,
            "score": receipt.score,
            "query_kind": receipt.query_kind,
            "query_hash": receipt.query_hash,
        }
        for label in labels
    ]


def _retrieved_excerpt_report(receipt: SnapshotRetrievalReceipt) -> dict[str, object]:
    """Project one actual retrieval receipt without fixture/gold labels."""

    return {
        "retrieval_evidence_id": receipt.resolved_evidence_id(),
        "source_filename": receipt.source_filename,
        "excerpt": receipt.excerpt or receipt.text,
        "query_kind": receipt.query_kind,
        "query_hash": receipt.query_hash,
        "rank": receipt.rank,
        "score": receipt.score,
    }


def _provider_ledger_rows(
    repository: ProviderRepository,
    *,
    scope_id: str,
    provider_operation: str,
) -> dict[str, object]:
    try:
        operations = tuple(
            item
            for item in repository.operations(scope_id=scope_id)
            if item.provider_operation == provider_operation
        )
    except Exception as exc:
        raise RealRAGRunError("ledger_read_failed") from exc
    return _ledger_rows_from_operations(operations, scope_id=scope_id)


def _ledger_rows_from_operations(
    operations: Sequence[object], *, scope_id: str | None = None
) -> dict[str, object]:
    """Project provider operations without exposing request or response data."""

    return {
        "scope_id": scope_id,
        "operation_count": len(operations),
        "requested_count": sum(int(getattr(item, "request_count", 0)) for item in operations),
        "charged_request_count": sum(
            int(getattr(item, "charged_request_count", 0)) for item in operations
        ),
        "states": {
            state: sum(1 for item in operations if getattr(item, "state", None) == state)
            for state in (
                "prepared",
                "reserved",
                "sending",
                "accepted",
                "succeeded",
                "not_sent",
                "acceptance_unknown",
                "failed",
            )
            if any(getattr(item, "state", None) == state for item in operations)
        },
    }


def _charged_request_total(report: Mapping[str, object]) -> int:
    """Read only numeric charged counts from one sanitized case report."""

    ledger = report.get("provider_ledger")
    if not isinstance(ledger, Mapping):
        return 0
    total = 0
    for operation in ("embedding", "query", "llm"):
        row = ledger.get(operation)
        if isinstance(row, Mapping):
            value = row.get("charged_request_count", 0)
            if isinstance(value, int) and not isinstance(value, bool) and value >= 0:
                total += value
    return total


def _attempt_report(outcome: object, *, default_count: int = 0) -> dict[str, object]:
    """Expose bounded repair accounting without provider response details."""

    raw_attempts = getattr(outcome, "attempts", ())
    count = len(raw_attempts) if isinstance(raw_attempts, Sequence) else default_count
    return {
        "attempt_count": count,
        "first_attempt_succeeded": count == 1 and getattr(outcome, "status", None) == "succeeded",
        "repair_count": max(0, count - 1),
    }


def _ledger_delta(database: Database, before_ids: set[str]) -> dict[str, object]:
    """Capture charged counts even when a case fails after provider I/O."""

    try:
        operations = tuple(
            item
            for item in ProviderRepository(database).operations()
            if str(getattr(item, "id", "")) not in before_ids
        )
    except Exception as exc:
        raise RealRAGRunError("ledger_read_failed") from exc
    return {
        name: _ledger_rows_from_operations(
            tuple(item for item in operations if item.provider_operation == operation),
        )
        for name, operation in (
            ("embedding", "embedding"),
            ("query", "embedding_query"),
            ("llm", "llm_debate_turn"),
        )
        if any(item.provider_operation == operation for item in operations)
    }


def _in_memory_llm_ledger(ledger: object, *, scope_id: str) -> dict[str, object]:
    """Project disabled-case ledger counts before an error leaves the scope."""

    try:
        operations_method = getattr(ledger, "operations", None)
        if not callable(operations_method):
            return {}
        operations = operations_method()
    except Exception:
        return {}
    return {"llm": _ledger_rows_from_operations(operations, scope_id=scope_id)}


