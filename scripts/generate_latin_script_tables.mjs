import { mkdirSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";

if (process.version !== "v24.14.0") {
  throw new Error(
    `Latin script table generation requires Node v24.14.0; received ${process.version}`,
  );
}

const root = resolve(import.meta.dirname, "..");
const defaultPythonOutput = resolve(
  root,
  "backend/app/modules/debates/generated/latin_script_ranges.py",
);
const defaultTypeScriptOutput = resolve(
  root,
  "frontend/lib/generated/latin-script-ranges.ts",
);

function argumentValue(name, fallback) {
  const index = process.argv.indexOf(name);
  return index === -1 ? fallback : process.argv[index + 1] || fallback;
}

const pythonOutput = resolve(
  root,
  argumentValue("--python-output", defaultPythonOutput),
);
const typeScriptOutput = resolve(
  root,
  argumentValue("--typescript-output", defaultTypeScriptOutput),
);

const isLetter = /^\p{Letter}$/u;
const isLatinScript = /^\p{Script_Extensions=Latin}$/u;

function latinLetterCodePoints() {
  const codePoints = [];
  for (let codePoint = 0; codePoint <= 0x10ffff; codePoint += 1) {
    const character = String.fromCodePoint(codePoint);
    if (isLetter.test(character) && isLatinScript.test(character)) {
      codePoints.push(codePoint);
    }
  }
  return codePoints;
}

function compressRanges(codePoints) {
  const ranges = [];
  if (codePoints.length === 0) return ranges;
  let start = codePoints[0];
  let end = start;
  for (const codePoint of codePoints.slice(1)) {
    if (codePoint === end + 1) {
      end = codePoint;
      continue;
    }
    ranges.push([start, end]);
    start = codePoint;
    end = codePoint;
  }
  ranges.push([start, end]);
  return ranges;
}

function hex(codePoint) {
  return `0x${codePoint.toString(16).toUpperCase().padStart(4, "0")}`;
}

function generatePython(ranges) {
  const rows = ranges.map(
    ([start, end]) => `    (${hex(start)}, ${hex(end)}),`,
  );
  return `# Generated by scripts/generate_latin_script_tables.mjs with Node v24.14.0 Unicode properties.
# Do not edit manually. Run scripts/generate_latin_script_tables.mjs to refresh.

from __future__ import annotations

from bisect import bisect_right

LATIN_SCRIPT_LETTER_RANGES: tuple[tuple[int, int], ...] = (
${rows.join("\n")}
)
_LATIN_SCRIPT_LETTER_STARTS = tuple(start for start, _end in LATIN_SCRIPT_LETTER_RANGES)


def is_latin_script_letter(codepoint: int) -> bool:
    """Return whether a code point is a Unicode Latin-script letter."""

    index = bisect_right(_LATIN_SCRIPT_LETTER_STARTS, codepoint) - 1
    return index >= 0 and codepoint <= LATIN_SCRIPT_LETTER_RANGES[index][1]
`;
}

function generateTypeScript(ranges) {
  const rows = ranges.map(([start, end]) => `  [${start}, ${end}],`);
  return `// Generated by scripts/generate_latin_script_tables.mjs with Node v24.14.0 Unicode properties.
// Do not edit manually. Run scripts/generate_latin_script_tables.mjs to refresh.

export const LATIN_SCRIPT_LETTER_RANGES: readonly (readonly [
  number,
  number,
])[] = [
${rows.join("\n")}
];
const LATIN_SCRIPT_LETTER_STARTS = LATIN_SCRIPT_LETTER_RANGES.map(
  ([start]) => start,
);

export function isLatinScriptLetter(codePoint: number): boolean {
  let low = 0;
  let high = LATIN_SCRIPT_LETTER_STARTS.length;
  while (low < high) {
    const middle = Math.floor((low + high) / 2);
    if (LATIN_SCRIPT_LETTER_STARTS[middle] <= codePoint) {
      low = middle + 1;
    } else {
      high = middle;
    }
  }
  const index = low - 1;
  return index >= 0 && codePoint <= LATIN_SCRIPT_LETTER_RANGES[index][1];
}
`;
}

const ranges = compressRanges(latinLetterCodePoints());
mkdirSync(dirname(pythonOutput), { recursive: true });
mkdirSync(dirname(typeScriptOutput), { recursive: true });
writeFileSync(pythonOutput, generatePython(ranges), "utf8");
writeFileSync(typeScriptOutput, generateTypeScript(ranges), "utf8");
console.log(
  `generated ${ranges.length} Latin-script letter ranges using ${process.version}`,
);
