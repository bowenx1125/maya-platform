export function pixelSupported(text: string): boolean {
  return [...text.toUpperCase()].every((char) => char in GLYPHS);
}

/**
 * Text in the table's pixel face. `scale` is the size of one pixel in CSS
 * pixels. Characters outside the face (a name in Chinese, say) fall back to
 * the table's plain type, so nobody's name is ever dropped.
 */
export function PixelText({
  text,
  scale = 3,
  className,
}: {
  text: string;
  scale?: number;
  className?: string;
}) {
  const upper = text.toUpperCase();
  if (!pixelSupported(upper))
    return (
      <span className={className} data-pixel-fallback="">
        {text}
      </span>
    );
  let x = 0;
  let path = "";
  for (const char of upper) {
    const glyph = GLYPHS[char];
    glyph.forEach((row, y) => {
      [...row].forEach((cell, column) => {
        if (cell === "#") path += `M${x + column} ${y}h1v1h-1z`;
      });
    });
    x += glyph[0].length + 1;
  }
  const width = Math.max(1, x - 1);
  return (
    <span className={className}>
      <svg
        aria-hidden="true"
        width={width * scale}
        height={7 * scale}
        viewBox={`0 0 ${width} 7`}
        shapeRendering="crispEdges"
        style={{ display: "block" }}
      >
        <path d={path} fill="currentColor" />
      </svg>
      <span className="sr-only">{text}</span>
    </span>
  );
}
